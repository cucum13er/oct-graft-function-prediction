"""
Merge the complete donor + recipient clinical feature table with OCT features.

The clinical input is generated by digital_complete_raw_data.py. This script
keeps the complete clinical feature names, adds a binary IGF/DGF outcome column,
and joins case-level OCT morphology features by normalized KTX case number.
"""

from __future__ import annotations

import argparse
import os
import re

import numpy as np
import pandas as pd


DEFAULT_DIR = "data/processed"
DEFAULT_COMPLETE_CLINICAL_CSV = os.path.join(
    DEFAULT_DIR,
    "kidney_features_X_complete.csv",
)
DEFAULT_ALL_OCT_CSV = os.path.join(
    DEFAULT_DIR,
    "oct_features_all_available_all.csv",
)
DEFAULT_BIOPSY_OCT_CSV = os.path.join(
    DEFAULT_DIR,
    "biopsy_oct_features_all.csv",
)
DEFAULT_OUT_ALL = os.path.join(
    DEFAULT_DIR,
    "kidney_features_complete_clinical_oct_all_available.csv",
)
DEFAULT_OUT_BIOPSY = os.path.join(
    DEFAULT_DIR,
    "kidney_features_complete_clinical_oct_biopsy.csv",
)

DROP_OCT_META_COLS = [
    "num_bscans_total",
    "picked_mask_path",
    "picked_lumen_area_um2",
    "num_bscans_used",
    "num_lumens_total",
    "num_nnd_total",
]

CASE_COL = "sample_id"
LABEL_COL = "DGF or IGF"
OUTCOME_COL = "IGF(0)/DGF(1)"
REQUIRED_COMPLETE_CLINICAL_COLS = {
    CASE_COL,
    "donor_cause_of_death_stroke",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Merge complete digitized clinical features with OCT lumen features "
            "for ML-ready case-level tables."
        )
    )
    parser.add_argument(
        "--complete-clinical-csv",
        default=DEFAULT_COMPLETE_CLINICAL_CSV,
    )
    parser.add_argument("--all-oct-csv", default=DEFAULT_ALL_OCT_CSV)
    parser.add_argument("--biopsy-oct-csv", default=DEFAULT_BIOPSY_OCT_CSV)
    parser.add_argument("--out-all", default=DEFAULT_OUT_ALL)
    parser.add_argument("--out-biopsy", default=DEFAULT_OUT_BIOPSY)
    parser.add_argument(
        "--pnf-policy",
        default="ignore",
        choices=["ignore", "dgf"],
        help=(
            "How to map PNF labels. Default ignore leaves PNF as NaN because "
            "primary nonfunction is distinct from strict DGF. Use dgf for a "
            "broader adverse-function binary endpoint."
        ),
    )
    parser.add_argument(
        "--how",
        default="inner",
        choices=["inner", "left", "right", "outer"],
        help="Merge mode. Default inner keeps cases present in both inputs.",
    )
    return parser.parse_args()


def normalize_case_id(value: object) -> str:
    text = str(value).strip()
    match = re.search(r"(\d+)", text)
    if match is None:
        return ""
    return f"KTX{int(match.group(1))}"


def parse_binary_outcome(value: object, pnf_policy: str = "ignore") -> float:
    if pd.isna(value):
        return np.nan
    text = str(value).strip().lower()
    if not text:
        return np.nan

    tokens = set(re.findall(r"[a-z]+", text))
    if "dgf" in tokens:
        return 1.0
    if "igf" in tokens or "sgf" in tokens:
        return 0.0
    if "pnf" in tokens and pnf_policy == "dgf":
        return 1.0
    return np.nan


def require_unique_cases(name: str, df: pd.DataFrame) -> None:
    duplicated = df.loc[df["case_num"].duplicated(), "case_num"].tolist()
    if duplicated:
        raise ValueError(f"{name} has duplicate case_num values: {sorted(set(duplicated))}")


def read_oct_features(path: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    if "case_num" not in df.columns:
        raise ValueError(f"{path} is missing required column: case_num")

    df = df.copy()
    df["case_num"] = df["case_num"].apply(normalize_case_id)
    df = df.drop(columns=[col for col in DROP_OCT_META_COLS if col in df.columns])
    return df


def read_complete_clinical_features(path: str, pnf_policy: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    missing = sorted(REQUIRED_COMPLETE_CLINICAL_COLS - set(df.columns))
    if missing:
        raise ValueError(f"{path} is missing required columns: {missing}")

    df = df.copy()
    df["case_num"] = df[CASE_COL].apply(normalize_case_id)
    if LABEL_COL in df.columns:
        df[OUTCOME_COL] = df[LABEL_COL].apply(
            lambda value: parse_binary_outcome(value, pnf_policy)
        )

    drop_cols = [col for col in [CASE_COL, LABEL_COL] if col in df.columns]
    return df.drop(columns=drop_cols)


def ordered_columns(df: pd.DataFrame, clinical_df: pd.DataFrame) -> list[str]:
    available_clinical_cols = [
        col
        for col in clinical_df.columns
        if col != "case_num" and col in df.columns
    ]
    donor_cols = [col for col in available_clinical_cols if col.startswith("donor_")]
    recipient_cols = [
        col for col in available_clinical_cols if col.startswith("recipient_")
    ]
    outcome_cols = [col for col in [OUTCOME_COL] if col in available_clinical_cols]
    other_clinical_cols = [
        col
        for col in available_clinical_cols
        if col not in {*donor_cols, *recipient_cols, *outcome_cols}
    ]
    clinical_cols = donor_cols + recipient_cols + other_clinical_cols + outcome_cols
    oct_cols = [
        col
        for col in df.columns
        if col not in {"case_num", *clinical_cols}
    ]
    return ["case_num"] + oct_cols + clinical_cols


def case_sort_key(series: pd.Series) -> pd.Series:
    return series.map(lambda value: int(re.search(r"(\d+)", str(value)).group(1)))


def merge_complete_clinical_oct(
    clinical_csv: str,
    oct_csv: str,
    how: str,
    pnf_policy: str,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    clinical_df = read_complete_clinical_features(clinical_csv, pnf_policy)
    oct_df = read_oct_features(oct_csv)

    require_unique_cases("complete_clinical_csv", clinical_df)
    require_unique_cases("oct_csv", oct_df)

    merged = oct_df.merge(clinical_df, on="case_num", how=how)
    merged = (
        merged[ordered_columns(merged, clinical_df)]
        .sort_values("case_num", key=case_sort_key)
        .reset_index(drop=True)
    )
    return merged, clinical_df, oct_df


def print_summary(
    label: str,
    merged: pd.DataFrame,
    clinical_df: pd.DataFrame,
    oct_df: pd.DataFrame,
) -> None:
    merged_cases = set(merged["case_num"])
    print(f"{label} merged cases:", len(merged_cases))

    clinical_missing = sorted(set(clinical_df["case_num"]) - merged_cases)
    oct_missing = sorted(set(oct_df["case_num"]) - merged_cases)
    if clinical_missing:
        print(
            f"{label} clinical cases not in merged output:",
            len(clinical_missing),
            preview_cases(clinical_missing),
        )
    if oct_missing:
        print(
            f"{label} OCT cases not in merged output:",
            len(oct_missing),
            preview_cases(oct_missing),
        )

    if OUTCOME_COL in merged.columns:
        missing_outcome = merged.loc[merged[OUTCOME_COL].isna(), "case_num"].tolist()
        if missing_outcome:
            print(f"{label} merged cases with missing binary outcome:", missing_outcome)


def preview_cases(cases: list[str], limit: int = 20) -> list[str]:
    if len(cases) <= limit:
        return cases
    return cases[:limit] + [f"... {len(cases) - limit} more"]


def save_csv(df: pd.DataFrame, path: str) -> None:
    output_dir = os.path.dirname(os.path.abspath(path))
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    df.to_csv(path, index=False)


def main() -> None:
    args = parse_args()

    all_merged, all_clinical, all_oct = merge_complete_clinical_oct(
        args.complete_clinical_csv,
        args.all_oct_csv,
        args.how,
        args.pnf_policy,
    )
    biopsy_merged, biopsy_clinical, biopsy_oct = merge_complete_clinical_oct(
        args.complete_clinical_csv,
        args.biopsy_oct_csv,
        args.how,
        args.pnf_policy,
    )

    save_csv(all_merged, args.out_all)
    save_csv(biopsy_merged, args.out_biopsy)

    print("Saved:", args.out_all, "shape:", all_merged.shape)
    print_summary("all_available", all_merged, all_clinical, all_oct)
    print("Saved:", args.out_biopsy, "shape:", biopsy_merged.shape)
    print_summary("biopsy", biopsy_merged, biopsy_clinical, biopsy_oct)


if __name__ == "__main__":
    main()
