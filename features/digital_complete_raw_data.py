"""
Digitize the complete donor + recipient clinical CSV.

Input is generated by build_complete_raw_kidney_data.py. The output keeps
sample_id and DGF/IGF label as strings, and converts donor/recipient fields to
numeric model-ready features.
"""

from __future__ import annotations

import argparse
import os
import re

import numpy as np
import pandas as pd


DEFAULT_IN_CSV = "data/processed/all_raw_kidney_data_complete.csv"
DEFAULT_OUT_X = "data/processed/kidney_features_X_complete.csv"

CASE_COL = "sample_id"
LABEL_COL = "DGF or IGF"

RACE_MAP = {
    "white": 1,
    "black": 2,
    "asian": 3,
    "hispanic": 4,
    "other": 5,
}

RRT_MODALITY_MAP = {
    "ckd": 0,
    "pd": 1,
    "hd": 2,
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Convert complete donor/recipient clinical CSV to numeric features."
    )
    parser.add_argument("--input-csv", default=DEFAULT_IN_CSV)
    parser.add_argument("--output-x", default=DEFAULT_OUT_X)
    parser.add_argument(
        "--drop-incomplete-hla",
        action="store_true",
        help="Drop rows where HLA profile cannot be split into cPRA/class I/class II.",
    )
    return parser.parse_args()


def norm_str(value: object) -> object:
    if pd.isna(value):
        return np.nan
    text = str(value).replace("\n", " ").replace("\r", " ").strip().lower()
    text = re.sub(r"\s+", " ", text)
    return text


def to_float(value: object) -> float:
    if pd.isna(value):
        return np.nan
    text = norm_str(value)
    if pd.isna(text) or text == "":
        return np.nan
    text = text.replace(",", "")
    match = re.search(r"[-+]?\d*\.?\d+", text)
    return float(match.group()) if match else np.nan


def is_no_biopsy(value: object) -> bool:
    text = norm_str(value)
    return not pd.isna(text) and ("no bx" in text or "no biopsy" in text)


def is_unknown(value: object) -> bool:
    text = norm_str(value)
    if pd.isna(text) or text == "":
        return True
    return "unknown" in text or "not reported" in text or text in {"n/a", "na", "nan"}


def race_to_code(value: object) -> int:
    text = norm_str(value)
    if pd.isna(text) or text == "":
        return RACE_MAP["other"]
    if "african" in text or "black" in text or "cameroon" in text or "ghana" in text:
        return RACE_MAP["black"]
    if "caucasian" in text or "white" in text or "irish" in text:
        return RACE_MAP["white"]
    if "asian" in text or "chinese" in text:
        return RACE_MAP["asian"]
    if (
        "hispanic" in text
        or "latino" in text
        or "south-american" in text
        or "puerto rican" in text
        or "salvadoran" in text
        or "spaniard" in text
    ):
        return RACE_MAP["hispanic"]
    return RACE_MAP["other"]


def yes_no_unknown(value: object) -> float:
    text = norm_str(value)
    if pd.isna(text) or text == "":
        return np.nan
    if text.startswith("yes"):
        return 1.0
    if text.startswith("no"):
        return 0.0
    if "unknown" in text:
        return np.nan
    return np.nan


def previous_kidney_transplant(value: object) -> float:
    text = norm_str(value)
    if pd.isna(text) or text == "" or "unknown" in text:
        return np.nan
    if text.startswith("no"):
        return 0.0
    if "nephrectomy" in text and "txp" not in text and "transplant" not in text:
        return 0.0
    if text.startswith("yes"):
        return 1.0
    if "ktx" in text or "ldkt" in text or "ddkt" in text or "renal txp" in text:
        return 1.0
    if re.search(r"\b\d{1,2}/\d{1,2}/\d{2,4}\b", text):
        return 1.0
    if re.search(r"\b20\d{2}-\d{2}-\d{2}\b", text):
        return 1.0
    return 0.0


def diabetes(value: object) -> float:
    parsed = yes_no_unknown(value)
    return parsed if not pd.isna(parsed) else np.nan


def sex_male(value: object) -> float:
    text = norm_str(value)
    if text == "m":
        return 1.0
    if text == "f":
        return 0.0
    return np.nan


def donor_dcd(value: object) -> float:
    text = norm_str(value)
    if text == "dcd":
        return 1.0
    if text == "dbd":
        return 0.0
    return np.nan


def donor_cause_of_death_stroke(value: object) -> float:
    text = norm_str(value)
    if text == "stroke":
        return 1.0
    if text == "other":
        return 0.0
    return np.nan


def ifta_level(value: object) -> float:
    text = norm_str(value)
    if pd.isna(text) or "unknown" in text or is_no_biopsy(text):
        return np.nan
    if "<5" in text:
        return 0.0
    if re.search(r"5\s*[-–]\s*25", text):
        return 1.0
    if re.search(r"26\s*[-–]\s*50", text):
        return 2.0
    if ">50" in text or "> 50" in text:
        return 3.0
    return np.nan


def severity_level(value: object) -> float:
    text = norm_str(value)
    if pd.isna(text) or "unknown" in text or is_no_biopsy(text):
        return np.nan
    if "none" in text:
        return 0.0
    if "mild" in text:
        return 1.0
    if "moderate" in text:
        return 2.0
    if "severe" in text:
        return 3.0
    return np.nan


def arteriolar_hyalinosis_level(value: object) -> float:
    text = norm_str(value)
    if pd.isna(text) or text == "":
        return 0.0
    return severity_level(value)


def absent_present(value: object) -> float:
    text = norm_str(value)
    if pd.isna(text) or "unknown" in text or is_no_biopsy(text):
        return np.nan
    if "absent" in text:
        return 0.0
    if "present" in text:
        return 1.0
    return np.nan


def parse_etiology(value: object) -> tuple[float, float, float, float, float]:
    text = norm_str(value)
    if pd.isna(text) or text == "" or "unknown" in text or "unclear" in text:
        return (np.nan, np.nan, np.nan, np.nan, np.nan)

    htn = int("htn" in text or "hypertensive" in text)
    dm = int("dm" in text or "diabetes" in text or "diabetic" in text or "t2dm" in text)
    pckd = int("pkd" in text or "pckd" in text or "polycystic" in text or "adpkd" in text)
    gn = int(
        "glomer" in text
        or "iga" in text
        or "fsgs" in text
        or "lupus" in text
        or "nephritis" in text
        or "anti-gbm" in text
        or "anca" in text
        or "membranous" in text
    )
    other = int(not any([htn, dm, pckd, gn]))
    return (htn, dm, pckd, gn, other)


def rrt_modality(value: object) -> float:
    text = norm_str(value)
    if pd.isna(text) or text == "" or "pre dialysis" in text or "ckd" in text:
        return float(RRT_MODALITY_MAP["ckd"])
    if "hd" in text or "ihd" in text:
        return float(RRT_MODALITY_MAP["hd"])
    if "pd" in text:
        return float(RRT_MODALITY_MAP["pd"])
    return np.nan


def combined_rrt_modality(ckd_esrd_value: object, modality_value: object) -> float:
    modality = rrt_modality(modality_value)
    if not pd.isna(modality):
        return modality
    text = norm_str(ckd_esrd_value)
    if pd.isna(text) or text == "":
        return np.nan
    if "ckd" in text or "pre" in text:
        return float(RRT_MODALITY_MAP["ckd"])
    return np.nan


def parse_hla_profile(value: object) -> tuple[float, float, float]:
    text = norm_str(value)
    if pd.isna(text) or text == "":
        return (np.nan, np.nan, np.nan)

    cpra_match = re.search(r"(?:c?pra)\s*:?\s*([0-9]+(?:\.[0-9]+)?)", text)
    class_i_match = re.search(r"class\s*i\s*:?\s*([0-9]+(?:\.[0-9]+)?)", text)
    class_ii_match = re.search(r"class\s*ii\s*:?\s*([0-9]+(?:\.[0-9]+)?)", text)

    cpra = float(cpra_match.group(1)) if cpra_match else np.nan
    class_i = float(class_i_match.group(1)) if class_i_match else np.nan
    class_ii = float(class_ii_match.group(1)) if class_ii_match else np.nan
    return (cpra, class_i, class_ii)


def load_clinical(path: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    df.columns = (
        df.columns.str.replace(r"[\r\n]+", " ", regex=True)
        .str.replace(r"\s+", " ", regex=True)
        .str.strip()
    )
    return df.dropna(axis=1, how="all").copy()


def digitize(df: pd.DataFrame) -> pd.DataFrame:
    out = pd.DataFrame(index=df.index)
    out[CASE_COL] = df[CASE_COL]
    if LABEL_COL in df.columns:
        out[LABEL_COL] = df[LABEL_COL]

    numeric_cols = {
        "donor_Age": "donor_age",
        "donor_Intitial Creatinine": "donor_init_creatinine",
        "donor_Terminal Creatinine": "donor_term_creatinine",
        "donor_Time of Cold ischemia ( In Minutes)": "donor_cold_ischemia_min",
        "donor_KDPI": "donor_kdpi",
        "donor_Number of Glomeruli": "donor_num_glom",
        "donor_# of globally sclerosed glomeruli": "donor_num_glob_scl",
        "donor_Number of arteries": "donor_num_arteries",
        "recipient_Age": "recipient_age",
        "recipient_BMI": "recipient_bmi",
    }
    for raw_col, feature_col in numeric_cols.items():
        if raw_col in df.columns:
            out[feature_col] = df[raw_col].apply(to_float)

    out["donor_sex_male"] = df["donor_Sex"].apply(sex_male)
    out["donor_dcd"] = df["donor_DCD or DBD"].apply(donor_dcd)
    out["donor_cause_of_death_stroke"] = df["donor_Cause of Death"].apply(
        donor_cause_of_death_stroke
    )
    out["donor_race_code"] = df["donor_Race/Ethnicity"].apply(race_to_code)
    out["donor_htn"] = df["donor_History Of Hypertension"].apply(yes_no_unknown)

    out["donor_ifta_level"] = df[
        "donor_Interstitial fibrosis (and tubular atrophy) = IFTA"
    ].apply(ifta_level)
    out["donor_vascular_disease_level"] = df["donor_Vascular disease"].apply(
        severity_level
    )
    out["donor_arteriolar_hyalinosis_level"] = df[
        "donor_Arterioral hylinosis"
    ].apply(arteriolar_hyalinosis_level)
    out["donor_cortical_necrosis"] = df["donor_Cortical necrosis"].apply(
        absent_present
    )
    out["donor_fibrin_thrombi"] = df["donor_Fibrin thrombi"].apply(absent_present)

    out["recipient_sex_male"] = df["recipient_Sex"].apply(sex_male)
    out["recipient_race_code"] = df["recipient_Race/Ethnicity"].apply(race_to_code)
    out["recipient_previous_kidney_txp"] = df["recipient_Previous Transplant?"].apply(
        previous_kidney_transplant
    )
    out["recipient_rrt_modality"] = [
        combined_rrt_modality(ckd, modality)
        for ckd, modality in zip(
            df["recipient_Pre dialysis (CKD) or ESRD at time of txp"],
            df["recipient_PD or HD if on RRTx"],
        )
    ]
    out["recipient_diabetes"] = df["recipient_Diabetes?"].apply(diabetes)

    etiology = df["recipient_Etiology of ESRD"].apply(parse_etiology)
    etiology_cols = [
        "recipient_etiology_htn",
        "recipient_etiology_dm",
        "recipient_etiology_pckd",
        "recipient_etiology_gn",
        "recipient_etiology_other",
    ]
    out[etiology_cols] = pd.DataFrame(etiology.tolist(), index=df.index)

    hla = df["recipient_HLA Profile"].apply(parse_hla_profile)
    out[["recipient_cpra", "recipient_hla_class_i", "recipient_hla_class_ii"]] = (
        pd.DataFrame(hla.tolist(), index=df.index)
    )

    return out


def main() -> None:
    args = parse_args()
    df = load_clinical(args.input_csv)

    required_cols = {
        CASE_COL,
        "donor_Sex",
        "donor_Race/Ethnicity",
        "donor_DCD or DBD",
        "donor_Cause of Death",
        "donor_History Of Hypertension",
        "donor_Interstitial fibrosis (and tubular atrophy) = IFTA",
        "donor_Vascular disease",
        "donor_Arterioral hylinosis",
        "donor_Cortical necrosis",
        "donor_Fibrin thrombi",
        "recipient_Sex",
        "recipient_Race/Ethnicity",
        "recipient_Etiology of ESRD",
        "recipient_Previous Transplant?",
        "recipient_Pre dialysis (CKD) or ESRD at time of txp",
        "recipient_PD or HD if on RRTx",
        "recipient_Diabetes?",
        "recipient_HLA Profile",
    }
    missing = sorted(required_cols - set(df.columns))
    if missing:
        raise ValueError(f"Input CSV is missing required columns: {missing}")

    out = digitize(df)

    hla_cols = ["recipient_cpra", "recipient_hla_class_i", "recipient_hla_class_ii"]
    incomplete_hla = out[hla_cols].isna().any(axis=1)
    if args.drop_incomplete_hla:
        out = out.loc[~incomplete_hla].copy()
    elif incomplete_hla.any():
        cases = out.loc[incomplete_hla, CASE_COL].tolist()
        print(f"Warning: incomplete HLA profile for {len(cases)} cases: {cases}")

    feature_cols = [col for col in out.columns if col not in {CASE_COL, LABEL_COL}]
    all_missing_cols = [col for col in feature_cols if out[col].isna().all()]
    if all_missing_cols:
        raise ValueError(f"Parsing produced all-NaN feature columns: {all_missing_cols}")

    output_dir = os.path.dirname(args.output_x)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    out.to_csv(args.output_x, index=False)

    print("Saved:", args.output_x, "shape:", out.shape)
    print("Feature columns:", feature_cols)


if __name__ == "__main__":
    main()
